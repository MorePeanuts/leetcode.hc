package main

// Floyd's tortoise and hare: the fast pointer meets the slow one exactly when
// the list has a cycle.
func hasCycle(head *ListNode) bool {
	slow, fast := head, head
	for fast != nil && fast.Next != nil {
		slow = slow.Next
		fast = fast.Next.Next
		if slow == fast {
			return true
		}
	}
	return false
}
